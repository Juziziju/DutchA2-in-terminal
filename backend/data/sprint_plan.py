def get_sprint_day(day: int) -> dict | None:
    """Return a single day's plan by day number (1-20)."""
    for d in SPRINT_DAYS:
        if d["day"] == day:
            return d
    return None


def get_sprint_phase(phase: int) -> dict | None:
    """Return a phase definition by phase number (1-3)."""
    for p in SPRINT_PHASES:
        if p["phase"] == phase:
            return p
    return None


def get_sprint_questions(day: int) -> list[dict]:
    """Return the speaking practice questions for a given sprint day."""
    d = get_sprint_day(day)
    if not d:
        return []
    return d.get("questions", [])


def get_sprint_overview() -> list[dict]:
    """Return all 20 days with phase info for overview display."""
    return [
        {**d, "phase_name": next(p["name_en"] for p in SPRINT_PHASES if p["phase"] == d["phase"])}
        for d in SPRINT_DAYS
    ]
