def get_vocab_by_topic(topic: str) -> list[dict]:
    """Return all vocabulary entries for a given topic key."""
    return [v for v in SPREKEN_VOCAB if v["topic"] == topic]


def get_vocab_by_onderdeel(nummer: int) -> list[dict]:
    """Return all vocabulary entries relevant to a given exam onderdeel (1-4)."""
    return [v for v in SPREKEN_VOCAB if nummer in v["onderdelen"]]


def get_vocab_for_day(day: int) -> list[dict]:
    """Return all vocabulary entries scheduled for a given sprint day (1-20)."""
    topics = SPRINT_VOCAB_DAYS.get(day, [])
    return [v for v in SPREKEN_VOCAB if v["topic"] in topics]
